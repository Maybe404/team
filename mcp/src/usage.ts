// 产品使用指南：给不熟悉 Loom 的成员和他们的 Agent 看。说明每个功能干什么、什么时候用，
// 以及哪些能通过 MCP 做、哪些要去网页上做。内容要和实际能力保持一致，改了工具记得同步这里。

export function usageGuide(webUrl: string, workspace: string): string {
  const w = `${webUrl}/${workspace}`;
  return `# Loom 使用指南

这个平台由 Agent 写入和维护，人是受益者：用来核验、学习、查看。所以所有内容都要让人能看懂、结构清晰、证据可核验。

网页入口：${w}/ 。下面按“要做什么事”来选功能。

## 层级

- 工作区：整个团队的空间，成员、项目都在里面。成员只有管理员和成员两种角色。
- 项目：通常对应一个产品或一个代码仓库。任务、文档、模块、视图、周期都属于某个项目。一个项目里再用模块区分版本和需求。项目成员要管理员在「项目设置 → 成员」里单独加。
- 经验库（LESSON）和每日回顾（REVIEW）是全员共享的项目，自动加入，不用手动加。

## 谁能改什么

- 工作项：创建人、指派人、管理员能改；其他成员只能评论。
- 页面：作者、管理员能改；其他成员只能阅读和评论。
- 想改别人的内容：评论里提出建议，让对方自己改（Agent 用 comment_task）。

## 工作项（任务）

一件具体要做的事，有编号（如 ABC-12）、状态、负责人、优先级、子任务、评论。
- 状态流转：待办 → 待开始 → 进行中 → 待审查 → 已完成；另有阻塞、待决定、已取消。
- 「已完成」「已取消」只能由人在网页上设置；Agent 做完改成「待审查」并在评论里写带证据的结论。
- MCP 能做：查、建、改、评论、挂子任务、指派（create_task、update_task、comment_task、list_tasks、get_task）。

## 页面（文档）

设计方案、会议纪要、复盘这类要长期留存的文字，放在项目的「页面」里。任务讲“做什么”，页面讲“为什么这么做”。
- MCP 能做：写、读、整篇更新、写入时用 task 参数关联到任务、或用 link_doc 关联已有文档（write_doc、read_doc、list_docs、link_doc），写入前会按规范检查。
- 关联：页面和工作项可以一键关联，两边都能看到，一个页面能关联多个工作项，一个工作项也能关联多个页面。网页上，工作项右侧「关联文档」、页面菜单「关联工作项」，弹窗里默认列出最近更新的，可以滚动选，也能搜索，点一下关联、再点一下取消；Agent 用 write_doc 的 task 参数或 link_doc。创建人、指派人、文档作者、管理员能建立关联。
- 页面里能放的内容：普通排版之外，输入 / 能插入「HTML 页面」块；语言为 mermaid 的代码块会渲染成流程图。Agent 写 Markdown 时，流程、时序、架构画成 mermaid，成品网页写成 html-embed 围栏（写法见 get_guide topic=writing）。HTML 块在网页上可以拖拽调大小、整页放大、下载。
- 想让团队外的人读：管理员在页面右上角「…」→「公开链接」打开，生成免登录只读链接，关掉就失效。这个只能在网页上做。

## 模块（Module）：整理任务的主要方式

一个项目里同时有好几个版本、好几个需求，任务多了就乱。用模块按**版本或需求**把任务分组：模块名写成“版本号 需求名”，例如“v1.2 登录改版”“v1.2 订单导出”“官网改版”。一个任务可以同时在多个模块里（比如同时属于需求模块和“线上问题”模块）。
- 为什么常用：看某个版本做到哪了、某个需求还剩几个任务、发版前哪些没做完，都按模块看；每个模块有状态、起止日期、负责人和完成进度。
- 和周期的区别：周期按时间切（这两周做什么），模块按主题切（这个版本、这个需求），两者可以同时用。
- 什么时候建：开始做一个版本或一个需求，预计拆成三个以上任务时，先建模块再建任务。
- MCP 能做：list_modules 看现有模块和进度；save_module 新建或修改（名称、说明、状态、起止日期、负责人）；create_task、update_task 的 modules 参数把任务放进模块，remove_modules 移出模块；list_tasks 的 module 参数按模块看任务，每条任务后面也会标出所属模块。
- 项目功能开关：模块、视图、周期要项目管理员在「项目设置 → 功能」里打开；新建的项目默认开启模块和视图。工具提示“没有开启”时，告诉用户去打开，不要换办法绕过。
- 约定：建任务前先 list_modules，有合适的就放进去，没有再 save_module 新建，不要重复建同名模块；模块状态“已完成”“已取消”由人在网页上设置，模块归档和删除也在网页上做。

## 视图（View）

保存下来的筛选和展示方式，比如“指派给我且进行中”“v1.2 的阻塞任务”“本周待审查（看板）”。每次不用重新筛，项目成员都能直接打开。
- 什么时候用：同一种筛选天天要看时；不熟悉系统的人，直接告诉 Agent 想看什么，让 Agent 建。
- MCP 能做：list_views 看现有视图（筛选条件会翻成一句话）；save_view 新建或修改自己建的视图：条件可以按状态、负责人、优先级、标签、模块、周期组合，展示方式可选列表、看板、日历、表格、甘特图，可分组、排序。
- 约定：建之前先 list_views，同样的条件别重复建；名称要让人一眼看出看的是什么；改别人建的视图要请对方来改。删除视图在网页上做。

## 周期（Cycle）

固定时间窗的冲刺，比如“两周一个周期”。适合有固定节奏的迭代：周期开始前把要做的任务放进来，结束时没做完的顺延，网页上能看燃尽图。
- 什么时候用：团队按固定节奏交付时。需求零散、随到随做的项目可以不用，用模块就够了。
- MCP 能做：list_tasks 的 cycle 参数按周期看任务、list_views 和 save_view 的筛选里也能按周期。周期的创建、把任务放进周期要在网页「周期」页做。

## 经验库

做完任务后沉淀下来的做法和教训。不是什么都往里放：要可复用、不明显、有代价、已验证，详细标准调用 get_guide（topic=lessons）。Agent 用 propose_lesson 提交，状态是「待审核」，人在网页上改成「已采纳」后才会被检索到。动手前先 search_lessons。

## 每日回顾

review_digest 汇总等你决定、阻塞、待审查、长期没动的任务和待审核的经验；publish=true 会写成「每日回顾」项目里你当天的个人回顾。全员的团队回顾每天定时自动生成。

## MCP 做不了、要去网页做的事

删除（只能归档）、成员和邀请、项目设置、关联代码仓库、创建周期和把任务放进周期、模块的归档和删除、视图的删除、公开链接、把任务或模块标成已完成或已取消。

## 新人上手顺序

1. 让 Agent 调用 whoami，确认账号和当前仓库的项目关联。
2. 在项目里建第一个任务，用 create_task，写清目标和验收标准。
3. 做完后 update_task 改成「待审查」，评论里写结论和证据。
4. 需要留存的方案用 write_doc 写成页面并关联到任务。
5. 开始一个版本或需求时，先 list_modules，没有合适的就 save_module 建一个，再用 modules 参数把任务放进去；常看的筛选用 save_view 存成视图。需要固定节奏排期时，再去网页上用周期。
`;
}
