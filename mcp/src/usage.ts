// 产品使用指南：给不熟悉 Plane 的成员和他们的 Agent 看。说明每个功能干什么、什么时候用，
// 以及哪些能通过 MCP 做、哪些要去网页上做。内容要和实际能力保持一致，改了工具记得同步这里。

export function usageGuide(webUrl: string, workspace: string): string {
  const w = `${webUrl}/${workspace}`;
  return `# 团队协作平台使用指南

网页入口：${w}/ 。下面按“要做什么事”来选功能。

## 层级

- 工作区：整个团队的空间，成员、项目都在里面。成员只有管理员和成员两种角色。
- 项目：通常对应一个产品或一个代码仓库。任务、文档、周期、模块、视图都属于某个项目。项目成员要管理员在「项目设置 → 成员」里单独加。
- 经验库（LESSON）和每日回顾（REVIEW）是全员共享的项目，自动加入，不用手动加。

## 工作项（任务）

一件具体要做的事，有编号（如 ABC-12）、状态、负责人、优先级、子任务、评论。
- 状态流转：待办 → 待开始 → 进行中 → 待审查 → 已完成；另有阻塞、待决定、已取消。
- 「已完成」「已取消」只能由人在网页上设置；Agent 做完改成「待审查」并在评论里写带证据的结论。
- MCP 能做：查、建、改、评论、挂子任务、指派（create_task、update_task、comment_task、list_tasks、search_tasks、get_task）。

## 页面（文档）

设计方案、会议纪要、复盘这类要长期留存的文字，放在项目的「页面」里。任务讲“做什么”，页面讲“为什么这么做”。
- MCP 能做：写、读、整篇更新、关联到任务（write_doc、read_doc、list_docs、link_doc），写入前会按规范检查。
- 想让团队外的人读：管理员在页面右上角「…」→「公开链接」打开，生成免登录只读链接，关掉就失效。这个只能在网页上做。

## 周期（Cycle）

固定时间窗的冲刺，比如“两周一个周期”。适合有节奏的迭代：周期开始前把要做的任务放进来，结束时没做完的任务可以顺延，网页上能看燃尽图。
- 什么时候用：团队按固定节奏交付时。需求零散、随到随做的项目可以不用。
- 当前 MCP 不能读写周期，在网页「周期」页创建，把任务拖进去或在任务里选择周期。

## 模块（Module）

一个功能或一个大需求，把跨时间、跨人的任务归在一起，比如“登录改版”“订单导出”。和周期的区别：周期按时间切，模块按主题切，一个任务可以同时在某个周期和某个模块里。
- 什么时候用：一个需求拆成了十几个任务，需要看整体进度时。
- 当前 MCP 不能读写模块，在网页「模块」页创建，任务里选择所属模块。

## 视图（View）

保存下来的筛选条件，比如“指派给我且进行中”“本周待审查”。每次不用重新筛，团队也可以共用同一个视图。
- 什么时候用：同一种筛选天天要看时。
- 当前 MCP 不能读写视图；想要同样的结果，可以让 Agent 用 list_tasks 按状态和负责人筛。

## 经验库

做完任务后沉淀下来的做法和教训。Agent 用 propose_lesson 提交，状态是「待审核」，人在网页上改成「已采纳」后才会被检索到。动手前先 search_lessons。

## 每日回顾

review_digest 汇总等你决定、阻塞、待审查、长期没动的任务和待审核的经验；publish=true 会写成「每日回顾」项目里你当天的个人回顾。全员的团队回顾每天定时自动生成。

## MCP 做不了、要去网页做的事

删除（只能归档）、成员和邀请、项目设置、关联代码仓库、周期、模块、视图、公开链接、把任务标成已完成或已取消。

## 新人上手顺序

1. 让 Agent 调用 whoami，确认账号和当前仓库的项目关联。
2. 在项目里建第一个任务，用 create_task，写清目标和验收标准。
3. 做完后 update_task 改成「待审查」，评论里写结论和证据。
4. 需要留存的方案用 write_doc 写成页面并关联到任务。
5. 觉得任务多了、需要排期时，再去网页上用周期和模块。
`;
}
